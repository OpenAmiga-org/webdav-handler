#!/usr/bin/env python3
"""Writes the AmiSSL glue of the AmigaOS 4 build. Public domain.

    python3 -I tools/gen_amissl_glue.py OUTDIR

AmiSSL 5 (OpenSSL 3, AMISSL_V3xx) and AmiSSL 6 (OpenSSL 4, AMISSL_V4xx) have
different interface tables, so the SDK's stub library (fixed AmiSSL 5
offsets) cannot be used if both are to work. Instead every function in
tools/amissl_functions.txt (the ones libcurl and the handler call) gets a
stub here that calls through amissl_fn[], which src/os4/amissl.c fills from
the opened interface using the offsets of that AmiSSL version:

    OUTDIR/amissl_glue.c    the stubs (prototypes from the AmiSSL 5 SDK's
                            amissl.xml; compiled with the AmiSSL 5 headers)
    OUTDIR/amissl_off_v3.c  offsetof() each function in the AmiSSL 5
                            interface (compiled with the AmiSSL 5 headers)
    OUTDIR/amissl_off_v4.c  the same for AmiSSL 6 (compiled with the AmiSSL 6
                            headers first), and AMISSL_V4xx; a function that
                            AmiSSL 6 no longer has (OpenSSL 4 dropped it from
                            the interface) gets the replacement wdv_v4_<name>
                            from src/os4/amissl_compat.c instead

The approach is the one of sftp-handler (its tools/gen_amissl_glue.py);
libcurl needs the replacements and the callback types on top.
tools/check_amissl_api.py checks the prototypes and the replacements.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
XML5 = os.path.join(ROOT, "build", "deps", "amissl-sdk", "AmiSSL", "Developer", "xml", "amissl.xml")
XML6 = os.path.join(ROOT, "build", "deps", "amissl6-sdk", "AmiSSL", "Developer", "xml", "amissl.xml")
LIST = os.path.join(ROOT, "tools", "amissl_functions.txt")

# functions AmiSSL 6 no longer has: src/os4/amissl_compat.c replaces them
V4_REPLACED = ("ASN1_STRING_length", "EVP_PKEY_get1_RSA", "MD5_Final", "MD5_Init", "MD5_Update",
               "RSA_flags", "RSA_free", "SSL_CTX_set_srp_password", "SSL_CTX_set_srp_username",
               "X509_get_pubkey")

# varargs functions: an interface cannot pass on "...", so these are
# written out here (on top of other functions of the list)
HANDWRITTEN = {
    "BIO_printf": """int BIO_printf(BIO *a0, const char *a1, ...)
{
	char buf[512], *big;
	va_list ap;
	int n, r;

	va_start(ap, a1);
	n = vsnprintf(buf, sizeof(buf), a1, ap);
	va_end(ap);
	if (n < 0)
		return -1;
	if ((size_t)n < sizeof(buf))
		return BIO_puts(a0, buf);
	big = malloc((size_t)n + 1);
	if (big == NULL)
		return -1;
	va_start(ap, a1);
	vsnprintf(big, (size_t)n + 1, a1, ap);
	va_end(ap);
	r = BIO_puts(a0, big);
	free(big);
	return r;
}
""",
}

HEAD = """/* Generated by tools/gen_amissl_glue.py - do not edit. Public domain. */
/* the AmiSSL interface marks deprecated functions too */
#pragma GCC diagnostic ignored "-Wdeprecated-declarations"
"""
INCLUDES = """#include <stddef.h>
#include <proto/amissl.h>
"""
OPENSSL = ["#include <openssl/%s.h>" % h for h in
           ("asn1", "bio", "bn", "crypto", "ec", "err", "evp", "md5", "ocsp", "pem", "pkcs12", "rand",
            "rsa", "ssl", "ui", "x509", "x509v3", "params")]


def functions():
    with open(LIST) as f:
        return [line.strip() for line in f if line.strip() and not line.startswith("#")]


def prototypes(path):
    with open(path, encoding="latin-1") as f:
        xml = f.read()
    protos = {}
    for m in re.finditer(r'<method\s+name="([^"]+)"\s+result="([^"]*)"[^>]*?(/>|>(.*?)</method>)', xml, re.S):
        args = re.findall(r'<arg\s+name="[^"]*"\s+type="([^"]*)"', m.group(4) or "")
        if "<vararg" in (m.group(4) or ""):
            args = args + ["..."]
        protos[m.group(1)] = (m.group(2), args)
    return protos


def main():
    out = sys.argv[1]
    os.makedirs(out, exist_ok=True)
    names = functions()
    protos = prototypes(XML5)
    have6 = prototypes(XML6)
    missing = [n for n in names if n not in protos]
    if missing:
        sys.exit("not in the AmiSSL 5 SDK: " + " ".join(missing))
    gone = [n for n in names if n not in have6 and n not in V4_REPLACED]
    if gone:
        sys.exit("not in AmiSSL 6 and no replacement in src/os4/amissl_compat.c: " + " ".join(gone))
    n = len(names)

    # callback types such as "int (*)(BIO *)" become typedefs
    typedefs = {}

    def ctype(t):
        if "(*)" not in t:
            return t
        if t not in typedefs:
            typedefs[t] = "amissl_cb%d" % len(typedefs)
        return typedefs[t]

    body = []
    for i, name in enumerate(names):
        res, types = protos[name]
        if name in HANDWRITTEN:
            body += [HANDWRITTEN[name]]
            continue
        for t in [res] + types:
            if "..." in t:
                sys.exit("%s: varargs, add its stub to HANDWRITTEN" % name)
        res_t = ctype(res)
        types_t = [ctype(t) for t in types]
        params = ", ".join("%s a%d" % (t, k) for k, t in enumerate(types_t)) or "void"
        fptr = "%s (*)(%s)" % (res_t, ", ".join(["struct AmiSSLIFace *"] + types_t))
        call = "((%s)amissl_fn[%d])(%s)" % (fptr, i, ", ".join(["IAmiSSL"] + ["a%d" % k for k in range(len(types))]))
        ret = "" if res.strip() == "void" else "return "
        body += ["%s %s(%s)" % (res_t, name, params), "{", "\t%s%s;" % (ret, call), "}", ""]
    glue = [HEAD, "#define OPENSSL_SUPPRESS_DEPRECATED", INCLUDES,
            "#include <stdarg.h>", "#include <stdio.h>", "#include <stdlib.h>"] + OPENSSL + [""]
    glue += ["typedef %s;" % t.replace("(*)", "(*%s)" % td, 1) for t, td in typedefs.items()]
    glue += ["", "/* filled by amissl_open() from the opened AmiSSL interface */",
             "void *amissl_fn[%d];" % n, "const int amissl_nfn = %d;" % n, ""]
    glue += ["/* index of each function in amissl_fn[] */"]
    glue += ["const int amissl_idx_%s = %d;" % (name, i) for i, name in enumerate(names)
             if name in V4_REPLACED or name == "SSL_get0_group_name"]
    glue += [""] + body
    with open(os.path.join(out, "amissl_glue.c"), "w") as f:
        f.write("\n".join(glue))

    v3 = [HEAD, "#define OPENSSL_SUPPRESS_DEPRECATED", INCLUDES, "#include <libraries/amisslmaster.h>", "",
          "const unsigned int amissl_off_v3[%d] = {" % n]
    v3 += ["\toffsetof(struct AmiSSLIFace, %s)," % name for name in names]
    v3 += ["};", ""]
    with open(os.path.join(out, "amissl_off_v3.c"), "w") as f:
        f.write("\n".join(v3))

    v4 = [HEAD, "#define OPENSSL_SUPPRESS_DEPRECATED", INCLUDES, "#include <libraries/amisslmaster.h>", ""]
    v4 += ["extern void wdv_v4_%s(void);" % name for name in names if name not in have6]
    v4 += ["", "/* offsets in the AmiSSL 6 interface; 0: replaced (amissl_repl_v4[]) */",
           "const unsigned int amissl_off_v4[%d] = {" % n]
    v4 += ["\t%s," % ("offsetof(struct AmiSSLIFace, %s)" % name if name in have6 else "0")
           for name in names]
    v4 += ["};", "", "void (*const amissl_repl_v4[%d])(void) = {" % n]
    v4 += ["\t%s," % ("NULL" if name in have6 else "wdv_v4_%s" % name) for name in names]
    v4 += ["};", "", "const int amissl_v4xx = AMISSL_V4xx;", ""]
    with open(os.path.join(out, "amissl_off_v4.c"), "w") as f:
        f.write("\n".join(v4))
    print("AmiSSL glue: %d functions, %d callback types, %d replaced for AmiSSL 6 -> %s"
          % (n, len(typedefs), len([x for x in names if x not in have6]), out))


if __name__ == "__main__":
    main()
